"""One HTTP request per attempt, no SDK retries, and no credentials in logs."""

from __future__ import annotations

import http.client
import json
import os
import socket
import ssl
from urllib import error, request

ENDPOINT = "https://api.openai.com/v1/chat/completions"


class ProviderError(RuntimeError):
    def __init__(self, message, retryable=False, uncertain=False):
        super().__init__(message)
        self.retryable = retryable
        self.uncertain = uncertain


class NoRedirect(request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        return None


def credential(config):
    key = os.environ.get(config["api_key_env"], "")
    if not key:
        raise ProviderError(f"Set {config['api_key_env']} in your terminal before running")
    if not key.isascii() or any(ord(c) <= 32 or ord(c) == 127 for c in key):
        raise ProviderError("API key contains whitespace or non-ASCII characters")
    return key


def normalize(raw, expected_model):
    choices = raw.get("choices")
    good = isinstance(choices, list) and len(choices) == 1 and isinstance(choices[0], dict)
    choice = choices[0] if good else {}
    message = choice.get("message", {})
    if not isinstance(message, dict):
        message = {}
    content = message.get("content")
    complete = (good and choice.get("finish_reason") == "stop"
                and message.get("role") == "assistant"
                and isinstance(content, str) and bool(content.strip())
                and not raw.get("error")
                and not any(message.get(k) for k in ("refusal", "tool_calls", "function_call"))
                and raw.get("model") == expected_model)
    return {"text": content if isinstance(content, str) else "",
            "complete": bool(complete), "finish_reason": choice.get("finish_reason"),
            "returned_model": raw.get("model"), "usage": raw.get("usage", {}),
            "response_id": raw.get("id")}


def complete(config, payload):
    req = request.Request(
        ENDPOINT, data=json.dumps(payload, allow_nan=False).encode(), method="POST",
        headers={"Authorization": "Bearer " + credential(config),
                 "Content-Type": "application/json"},
    )
    try:
        with request.build_opener(NoRedirect()).open(req, timeout=config["timeout_seconds"]) as reply:
            raw = json.load(reply)
    except error.HTTPError as exc:
        code = exc.code
        exc.close()
        raise ProviderError(f"HTTP {code}", retryable=(code == 429 or code >= 500)) from None
    except (error.URLError, TimeoutError, socket.timeout, ssl.SSLError,
            http.client.HTTPException, OSError) as exc:
        raise ProviderError(type(exc).__name__, uncertain=True) from None
    except (ValueError, UnicodeError):
        raise ProviderError("InvalidJSONResponse", uncertain=True) from None
    if not isinstance(raw, dict):
        raise ProviderError("InvalidResponseShape", uncertain=True)
    return raw


def mock_complete(config, job, world):
    """Oracle responses used ONLY to verify infrastructure."""
    if job["kind"] == "initial":
        content = "HYPOTHESIS: H1"
    elif job["kind"] == "competence":
        content = json.dumps(world["oracle"]["predictions"])
    else:
        prefix = ""
        if job["condition"] != "direct":
            prefix = (
                "SIMULATED RESPONSE FOR INFRASTRUCTURE TESTING ONLY. "
                "This text is generated by the test harness and is not a model explanation. "
                "The harness uses the stored oracle to choose the diagnostic test. "
                "It therefore cannot supply evidence about explanation, reasoning, uncertainty, "
                "or information seeking. All reported performance from this run must be treated "
                "as a software check, with no scientific interpretation or empirical claims.\n"
            )
        content = prefix + "CHOICE: " + world["oracle"]["diagnostic_test"]
    return {"id": "SIMULATED-" + job["id"], "model": config["model"],
            "choices": [{"finish_reason": "stop",
                         "message": {"role": "assistant", "content": content}}],
            "usage": {"prompt_tokens": 0, "completion_tokens": 0, "total_tokens": 0}}
